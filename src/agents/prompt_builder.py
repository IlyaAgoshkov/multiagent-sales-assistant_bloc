"""
PromptBuilder — централизованное место для сборки системных промптов агентов.

Каждый метод возвращает готовый system-prompt строкой.
Вынесено из агентов, чтобы шаблоны легко тестировались и редактировались.
"""

from __future__ import annotations


class PromptBuilder:
    """Строитель системных промптов для всех агентов системы."""

    # ── Appeal Analysis ──────────────────────────────────────────────────────

    @staticmethod
    def appeal_analysis_system() -> str:
        """
        Системный промпт агента обработки обращений клиента.

        Исправления (fix):
        - Добавлена строка контекста роли (role context).
        - Явно указан обязательный формат ответа — JSON.
        """
        return (
            "Ты — интеллектуальный агент CRM-системы ремонтной компании, "
            "специализирующийся на классификации и анализе входящих обращений клиентов.\n\n"
            "Твоя задача — классифицировать обращение по следующим параметрам:\n"
            "  • intent   — намерение клиента (строка, например: renovation_quote, complaint, info_request)\n"
            "  • urgency  — срочность: low | medium | high\n"
            "  • category — категория услуги (строка, например: kitchen, bathroom, full_renovation)\n"
            "  • recognized — удалось ли распознать обращение (boolean)\n\n"
            "ВАЖНО: Ответ ОБЯЗАТЕЛЬНО верни строго в формате JSON и ничего кроме JSON.\n"
            "Пример корректного ответа:\n"
            '{"intent": "renovation_quote", "urgency": "high", '
            '"category": "kitchen", "recognized": true}'
        )

    # ── Recommendation ───────────────────────────────────────────────────────

    @staticmethod
    def recommendation_system() -> str:
        """Системный промпт агента формирования рекомендаций менеджеру."""
        return (
            "Ты — опытный консультант по продажам ремонтной компании. "
            "На основе данных клиента, истории взаимодействий и корпоративной базы знаний "
            "сформулируй 3–5 конкретных рекомендаций менеджеру для работы с клиентом. "
            "Рекомендации должны быть краткими, практичными и применимыми немедленно."
        )

    # ── Commercial Offer ─────────────────────────────────────────────────────

    @staticmethod
    def commercial_offer_system() -> str:
        """Системный промпт агента подготовки коммерческого предложения."""
        return (
            "Ты — менеджер по продажам ремонтной компании. "
            "Составь коммерческое предложение строго в формате JSON:\n"
            '{"title": "...", "services": [{"name": "...", "price": 0}], '
            '"total": 0, "note": "..."}\n'
            "Используй только услуги и цены из предоставленного прайс-листа. "
            "Ответ должен содержать только JSON без пояснений."
        )

    # ── Deal Prediction ──────────────────────────────────────────────────────

    @staticmethod
    def deal_prediction_system() -> str:
        """Системный промпт агента прогнозирования вероятности сделки."""
        return (
            "Ты — аналитик продаж ремонтной компании. "
            "На основе обращения клиента и базовой конверсии по каналу "
            "оцени вероятность (от 0 до 100) успешного заключения сделки. "
            "Верни ответ строго в формате JSON:\n"
            '{"probability": 0.0, "rationale": "..."}\n'
            "Вероятность — вещественное число от 0 до 100. Ответ — только JSON."
        )

    # ── Self-Learning ────────────────────────────────────────────────────────

    @staticmethod
    def self_learning_system() -> str:
        """Системный промпт агента самообучения."""
        return (
            "Ты — аналитик продаж ремонтной компании. "
            "На основе успешных и неуспешных сделок сформулируй 3 новых практических совета "
            "для менеджеров. Верни ответ строго в формате JSON:\n"
            '{"category": "learned_tips", "content": "..."}\n'
            "Ответ — только JSON."
        )
